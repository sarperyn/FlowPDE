"""
Benchmark Data Generation Configs for FlowPDE
==============================================

Four named configs for reproducible, citable experiments.

Usage:
    from configs.benchmark_configs import DARCY_FNO, BURGERS_FNO, BURGERS_ROM, POISSON_SANITY
    train_data = DARCY_FNO.generator().generate(num_samples=1000, seed=0)
    test_data  = DARCY_FNO.generator().generate(num_samples=200,  seed=1)

Each config carries:
    - The dataclass config (fully reproducible, serialisable)
    - .generator()  — returns the corresponding Generator object
    - .cite         — the paper(s) this config is aligned with
    - .notes        — what the config is for / what to expect
"""

from dataclasses import dataclass
from typing import Any, Dict


# ─────────────────────────────────────────────────────────────────────────────
# Internal helpers
# ─────────────────────────────────────────────────────────────────────────────

@dataclass
class BenchmarkEntry:
    config: Any          # BurgersConfig / DarcyConfig / PoissonConfig
    generator_cls: Any   # BurgersGenerator / DarcyGenerator / PoissonGenerator
    cite: str
    notes: str

    def generator(self):
        return self.generator_cls(config=self.config)

    def info(self) -> Dict[str, str]:
        return {"cite": self.cite, "notes": self.notes, "config": str(self.config)}


# ─────────────────────────────────────────────────────────────────────────────
# 1.  Darcy Flow 2D  — FNO benchmark
# ─────────────────────────────────────────────────────────────────────────────
# Reference: Li et al., "Fourier Neural Operator for Parametric PDEs",
#            ICLR 2021.  https://arxiv.org/abs/2010.08895
#
# The FNO benchmark generates  −∇·(κ ∇u) = f  on [0,1]²  with:
#   κ ~ log-normal GRF  (α=2, τ=3)
#   f ~ constant 1  (but learning with random f is a harder, valid extension)
#   Dirichlet BC:  u = 0 on ∂Ω
#
# Standard split:  1000 train / 200 test, 64×64 grid.
# FNO achieves ~1% relative L2.  You don't need to match it exactly —
# you are solving the harder parametric (varying κ AND f) version.
#
from flowpde.datasets.exponax import DarcyGenerator
from flowpde.datasets.exponax.darcy import DarcyConfig

_DARCY_FNO_CFG = DarcyConfig(
    num_spatial_dims=2,
    num_points=64,          # 64×64  — standard FNO resolution
    domain_extent=1.0,      # [0,1]² — standard Darcy domain
    num_samples=1000,       # override at call time if you want 200 for test
    seed=42,
    # κ GRF: exact FNO parameters
    kappa_alpha=2.0,
    kappa_tau=3.0,
    kappa_scale=1.0,        # log-contrast:  κ ∈ [e^{-2}, e^{2}] ≈ [0.14, 7.4]
    kappa_min=0.1,
    # f: random source (wider distribution than the original f=1 benchmark,
    #    but standard in operator-learning extensions)
    f_cutoff_min=3,
    f_cutoff_max=12,        # keep moderate so solutions stay smooth
    f_amplitude_min=0.5,
    f_amplitude_max=3.0,
    f_gaussian_bump_prob=0.3,
    f_gaussian_bump_max_bumps=3,
    # CG solver: 500 iterations is conservative for 64×64
    cg_steps=500,
    torch_device='cpu',
)

DARCY_FNO = BenchmarkEntry(
    config=_DARCY_FNO_CFG,
    generator_cls=DarcyGenerator,
    cite=(
        "Li et al., 'Fourier Neural Operator for Parametric PDEs', ICLR 2021. "
        "kappa_alpha=2, kappa_tau=3 exactly matches the FNO Darcy benchmark."
    ),
    notes=(
        "64×64 grid, [0,1]² domain. "
        "Generate 1000 train (seed=0) + 200 test (seed=1). "
        "Report relative L2 error.  FNO reference: ~1%."
    ),
)


# ─────────────────────────────────────────────────────────────────────────────
# 2.  Burgers 1D  — FNO benchmark  (single viscosity, direct comparison)
# ─────────────────────────────────────────────────────────────────────────────
# Reference: Li et al., ICLR 2021 (same paper).
#
# FNO Burgers: 1D, ν = 0.01, periodic BC, T = 1.0, N = 1024.
# Data is generated by a fine spectral solver and sub-sampled.
# Exponax's ETDRK stepper is spectrally exact so there is no sub-sampling
# needed; N=1024 is directly usable.
#
# Standard split: 1000 train / 200 test.
# FNO achieves ~0.5% relative L2.
#
from flowpde.datasets.exponax import BurgersGenerator
from flowpde.datasets.exponax.burgers import BurgersConfig

_BURGERS_FNO_CFG = BurgersConfig(
    num_spatial_dims=1,
    num_points=1024,        # standard FNO resolution
    domain_extent=1.0,
    num_samples=1000,
    seed=42,
    dt=0.001,
    num_steps=1000,         # T = 1.0  (1000 × 0.001)
    # Single viscosity regime — matches FNO exactly
    diffusivity_min=0.01,
    diffusivity_max=0.01,   # fixed ν = 0.01
    convection_scale=1.0,
    single_channel=True,
    # ICs: truncated Fourier series only (no bumps) for cleaner comparison
    ic_cutoff_min=3,
    ic_cutoff_max=20,
    ic_max_one=False,
    amplitude_min=0.5,
    amplitude_max=2.0,
    gaussian_bump_prob=0.0, # Fourier-only ICs
    store_trajectory=False,
    torch_device='cpu',
)

BURGERS_FNO = BenchmarkEntry(
    config=_BURGERS_FNO_CFG,
    generator_cls=BurgersGenerator,
    cite=(
        "Li et al., 'Fourier Neural Operator for Parametric PDEs', ICLR 2021. "
        "ν=0.01, N=1024, T=1.0 matches the FNO 1D Burgers benchmark."
    ),
    notes=(
        "1D, 1024 points, T=1.0, fixed ν=0.01.  "
        "Generate 1000 train (seed=0) + 200 test (seed=1).  "
        "Use this only for direct comparison.  FNO reference: ~0.5% rel L2."
    ),
)


# ─────────────────────────────────────────────────────────────────────────────
# 3.  Burgers 1D  — Parametric ROM  (multi-viscosity, your main contribution)
# ─────────────────────────────────────────────────────────────────────────────
# This is the core ROM experiment.  A single surrogate model learns IC → u(T)
# across a 2-order-of-magnitude range of viscosities:
#
#   ν ∈ [1e-4, 1e-2]  (log-uniform)
#
# The three physical regimes covered:
#   ν = 1e-2  →  smooth, diffusion-dominated
#   ν = 1e-3  →  moderate nonlinearity, developing shocks
#   ν = 1e-4  →  near-inviscid, strong shocks / sharp gradients
#
# There is no single FNO paper to compare against here because FNO trains
# per-ν.  Instead cite:
#   - Kochkov et al. (learned simulators) or
#   - Wan et al., "Evolving reservoir computers for the prediction of
#     spatiotemporal dynamics", or the ROM survey by Rozza et al.
# and frame it as: "unlike FNO which requires retraining for each ν,
# our flow surrogate handles the full parametric family."
#
_BURGERS_ROM_CFG = BurgersConfig(
    num_spatial_dims=1,
    num_points=256,         # 256 is a good balance: captures shocks, trains fast
    domain_extent=1.0,
    num_samples=2000,       # larger set because the parameter space is wider
    seed=42,
    dt=0.001,
    num_steps=1000,         # T = 1.0  — same as FNO for fair comparison
    # Parametric range: 2 orders of magnitude
    diffusivity_min=1e-4,
    diffusivity_max=1e-2,
    convection_scale=1.0,
    single_channel=True,
    ic_cutoff_min=3,
    ic_cutoff_max=20,
    ic_max_one=False,
    amplitude_min=0.5,
    amplitude_max=2.5,
    gaussian_bump_prob=0.5,
    gaussian_bump_max_bumps=5,
    store_trajectory=False,
    torch_device='cpu',
)

BURGERS_ROM = BenchmarkEntry(
    config=_BURGERS_ROM_CFG,
    generator_cls=BurgersGenerator,
    cite=(
        "Parametric ROM extension.  ν sampled log-uniformly over [1e-4, 1e-2] "
        "following the convention in e.g. Hesthaven & Ubbiali (2018) and "
        "Wang et al. 'Recurrent neural network closure of parametric POD-Galerkin "
        "reduced-order models based on the Mori-Zwanzig formalism', JCP 2020."
    ),
    notes=(
        "1D, 256 points, T=1.0, ν ~ LogUniform(1e-4, 1e-2).  "
        "Generate 2000 train (seed=0) + 400 test (seed=1).  "
        "Report rel L2 error overall AND broken down by ν regime: "
        "[1e-4, 1e-3], [1e-3, 5e-3], [5e-3, 1e-2]."
    ),
)


# ─────────────────────────────────────────────────────────────────────────────
# 4.  Poisson 2D  — sanity check / baseline
# ─────────────────────────────────────────────────────────────────────────────
# Poisson is a static linear PDE: ∇²u = f.  The flow should learn this
# almost perfectly.  Use it to:
#   (a) verify the training pipeline works before touching Burgers/Darcy
#   (b) show a simple baseline in the report before harder experiments
#
from flowpde.datasets.exponax import PoissonGenerator
from flowpde.datasets.exponax.poisson import PoissonConfig

_POISSON_SANITY_CFG = PoissonConfig(
    num_spatial_dims=2,
    num_points=64,
    domain_extent=1.0,
    num_samples=1000,
    seed=42,
    order=2,                # standard Laplacian
    ic_cutoff_min=3,
    ic_cutoff_max=12,
    ic_max_one=False,
    amplitude_min=0.5,
    amplitude_max=3.0,
    gaussian_bump_prob=0.4,
    gaussian_bump_max_bumps=4,
    torch_device='cpu',
)

POISSON_SANITY = BenchmarkEntry(
    config=_POISSON_SANITY_CFG,
    generator_cls=PoissonGenerator,
    cite="No specific benchmark; use as sanity check.  Poisson is a linear PDE — expect <1% rel L2.",
    notes=(
        "2D, 64×64, periodic Laplacian.  "
        "Generate 1000 train (seed=0) + 200 test (seed=1).  "
        "If the model fails here, something is wrong with the pipeline."
    ),
)


# ─────────────────────────────────────────────────────────────────────────────
# Convenience dict
# ─────────────────────────────────────────────────────────────────────────────
ALL_BENCHMARKS = {
    "darcy_fno":    DARCY_FNO,
    "burgers_fno":  BURGERS_FNO,
    "burgers_rom":  BURGERS_ROM,
    "poisson":      POISSON_SANITY,
}


def list_benchmarks():
    """Print a summary of all available benchmarks."""
    print(f"{'Name':<20} {'Notes'}")
    print("-" * 80)
    for name, entry in ALL_BENCHMARKS.items():
        print(f"{name:<20} {entry.notes[:60]}...")
